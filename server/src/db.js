const LANG_COLUMN = { en: 0, pl: 1 };
export const personalName = (lang) => (lang === 'pl' ? 'Osobisty' : 'Personal');

export function createTracker(ownerId, name, currency = 'PLN', lang = 'en') {
  const id = Number(db.prepare('INSERT INTO trackers (name, currency, owner_id) VALUES (?, ?, ?)').run(name, currency, ownerId).lastInsertRowid);
  db.prepare("INSERT INTO tracker_members (tracker_id, user_id, role) VALUES (?, ?, 'owner')").run(id, ownerId);
  const ins = db.prepare('INSERT INTO categories (tracker_id, name, icon, color) VALUES (?, ?, ?, ?)');
  const col = LANG_COLUMN[lang] ?? 0;
  for (const c of DEFAULT_CATEGORIES) ins.run(id, c[col], c[2], c[3]);
  return id;
}

/** Give data created before accounts existed to the first registered user. Returns true if anything was claimed. */
export function claimLegacyData(userId) {
  const orphans = db.prepare('SELECT id FROM trackers WHERE owner_id IS NULL').all();
  for (const t of orphans) {
    db.prepare('UPDATE trackers SET owner_id = ? WHERE id = ?').run(userId, t.id);
    db.prepare("INSERT OR IGNORE INTO tracker_members (tracker_id, user_id, role) VALUES (?, ?, 'owner')").run(t.id, userId);
  }
  for (const t of ['holdings', 'piggy_accounts', 'portfolio_snapshots']) {
    db.prepare(`UPDATE ${t} SET user_id = ? WHERE user_id IS NULL`).run(userId);
  }
  return orphans.length > 0;
}

export function getSetting(key) {
  return db.prepare('SELECT value FROM settings WHERE key = ?').get(key)?.value;
}
