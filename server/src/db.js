import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';

const dbPath = process.env.DB_PATH || path.resolve(import.meta.dirname, '../data/finance.db');
fs.mkdirSync(path.dirname(dbPath), { recursive: true });

export const db = new DatabaseSync(dbPath);
db.exec('PRAGMA journal_mode = WAL;');

const SCHEMA_VERSION = 7;

const SCHEMA = `
CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  username      TEXT NOT NULL UNIQUE COLLATE NOCASE,
  name          TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  base_currency TEXT NOT NULL DEFAULT 'PLN',  -- for investments, piggybank, net worth
  created_at    TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at INTEGER NOT NULL                -- epoch ms
);

-- a spending tracker ("Personal", "Household", ...) that one or more users share
CREATE TABLE IF NOT EXISTS trackers (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  name       TEXT NOT NULL,
  currency   TEXT NOT NULL DEFAULT 'PLN',
  owner_id   INTEGER REFERENCES users(id) ON DELETE CASCADE,  -- NULL only for data migrated before accounts existed
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS tracker_members (
  tracker_id INTEGER NOT NULL REFERENCES trackers(id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('owner','member')),
  added_at   TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (tracker_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_members_user ON tracker_members(user_id);

CREATE TABLE IF NOT EXISTS categories (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  tracker_id    INTEGER NOT NULL REFERENCES trackers(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  icon          TEXT NOT NULL DEFAULT '•',
  color         TEXT NOT NULL DEFAULT '#2a78d6',
  monthly_limit REAL,
  archived      INTEGER NOT NULL DEFAULT 0,
  UNIQUE (tracker_id, name)
);

CREATE TABLE IF NOT EXISTS transactions (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  tracker_id  INTEGER NOT NULL REFERENCES trackers(id) ON DELETE CASCADE,
  date        TEXT NOT NULL,              -- YYYY-MM-DD
  amount      REAL NOT NULL CHECK (amount > 0),
  kind        TEXT NOT NULL DEFAULT 'expense' CHECK (kind IN ('expense','income')),
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  note        TEXT NOT NULL DEFAULT '',
  created_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
  client_id   TEXT,                       -- id generated by the app for offline entries (dedupes retried syncs)
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_tx_tracker_date ON transactions(tracker_id, date);

-- money prepared for a given month, per tracker
CREATE TABLE IF NOT EXISTS budgets (
  tracker_id INTEGER NOT NULL REFERENCES trackers(id) ON DELETE CASCADE,
  month      TEXT NOT NULL,              -- YYYY-MM
  amount     REAL NOT NULL CHECK (amount >= 0),
  note       TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (tracker_id, month)
);

CREATE TABLE IF NOT EXISTS holdings (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id     INTEGER REFERENCES users(id) ON DELETE CASCADE,
  symbol      TEXT NOT NULL,              -- Yahoo Finance symbol, e.g. PKN.WA, AAPL, VWCE.DE
  ticker      TEXT NOT NULL DEFAULT '',   -- as typed by the user, e.g. PKN.PL
  name        TEXT NOT NULL DEFAULT '',
  quantity    REAL NOT NULL,
  avg_price   REAL NOT NULL DEFAULT 0,    -- per unit, in instrument currency
  currency    TEXT NOT NULL DEFAULT '',   -- instrument currency (filled from quote)
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS price_cache (
  symbol     TEXT PRIMARY KEY,
  price      REAL NOT NULL,
  prev_close REAL,
  currency   TEXT NOT NULL,
  name       TEXT NOT NULL DEFAULT '',
  fetched_at INTEGER NOT NULL             -- epoch ms
);

-- daily snapshot of a user's total portfolio value for the history chart
CREATE TABLE IF NOT EXISTS portfolio_snapshots (
  user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  date    TEXT NOT NULL,
  value   REAL NOT NULL,
  cost    REAL NOT NULL,
  PRIMARY KEY (user_id, date)
);

CREATE TABLE IF NOT EXISTS piggy_accounts (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id    INTEGER REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  type       TEXT NOT NULL DEFAULT 'bank' CHECK (type IN ('cash','bank','savings','deposit','other')),
  currency   TEXT NOT NULL DEFAULT 'PLN',
  balance    REAL NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS piggy_history (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  account_id INTEGER NOT NULL REFERENCES piggy_accounts(id) ON DELETE CASCADE,
  balance    REAL NOT NULL,
  date       TEXT NOT NULL DEFAULT (date('now'))
);
`;

const tableExists = (t) => !!db.prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?").get(t);
const hasColumn = (t, c) => db.prepare(`PRAGMA table_info(${t})`).all().some((x) => x.name === c);

/**
 * v1 (single user, no trackers) -> v2. Old rows move into an ownerless "Personal" tracker;
 * the first account registered afterwards claims them (see claimLegacyData).
 */
function migrateFromV1() {
  const oldTables = ['categories', 'transactions', 'budgets', 'holdings', 'portfolio_snapshots', 'piggy_accounts', 'piggy_history'];
  for (const t of oldTables) if (tableExists(t)) db.exec(`ALTER TABLE ${t} RENAME TO ${t}_v1`);
  db.exec(SCHEMA);

  const ccy = db.prepare("SELECT value FROM settings WHERE key = 'base_currency'").get()?.value || 'PLN';
  const trackerId = db.prepare("INSERT INTO trackers (name, currency, owner_id) VALUES ('Personal', ?, NULL)").run(ccy).lastInsertRowid;

  if (tableExists('categories_v1')) db.prepare(`INSERT INTO categories (id, tracker_id, name, icon, color, monthly_limit, archived)
    SELECT id, ?, name, icon, color, monthly_limit, archived FROM categories_v1`).run(trackerId);
  if (tableExists('transactions_v1')) db.prepare(`INSERT INTO transactions (id, tracker_id, date, amount, kind, category_id, note, created_at)
    SELECT id, ?, date, amount, kind, category_id, note, created_at FROM transactions_v1`).run(trackerId);
  if (tableExists('budgets_v1')) db.prepare(`INSERT INTO budgets (tracker_id, month, amount, note)
    SELECT ?, month, amount, note FROM budgets_v1`).run(trackerId);
  if (tableExists('portfolio_snapshots_v1')) db.exec(`INSERT INTO portfolio_snapshots (date, value, cost)
    SELECT date, value, cost FROM portfolio_snapshots_v1`);
  if (tableExists('piggy_accounts_v1')) db.exec(`INSERT INTO piggy_accounts (id, name, type, currency, balance, updated_at)
    SELECT id, name, type, currency, balance, updated_at FROM piggy_accounts_v1`);
  if (tableExists('piggy_history_v1')) db.exec(`INSERT INTO piggy_history (id, account_id, balance, date)
    SELECT id, account_id, balance, date FROM piggy_history_v1`);

  for (const t of oldTables) if (tableExists(`${t}_v1`)) db.exec(`DROP TABLE ${t}_v1`);
  db.exec("DELETE FROM settings WHERE key IN ('base_currency', 'session_secret')");
}

const version = db.prepare('PRAGMA user_version').get().user_version;
if (version < SCHEMA_VERSION) {
  db.exec('PRAGMA foreign_keys = OFF; BEGIN');
  try {
    if (version < 2) {
      if (tableExists('categories') && !hasColumn('categories', 'tracker_id')) migrateFromV1();
      else db.exec(SCHEMA);
    }
    // v3: offline sync
    if (!hasColumn('transactions', 'client_id')) db.exec('ALTER TABLE transactions ADD COLUMN client_id TEXT');
    db.exec('CREATE UNIQUE INDEX IF NOT EXISTS idx_tx_client ON transactions(tracker_id, client_id)');
    // v5: machine translation (added in v4) was removed again
    db.exec('DROP TABLE IF EXISTS translation_cache');
    if (hasColumn('users', 'lang')) db.exec('ALTER TABLE users DROP COLUMN lang');
    // v6: salary calculator (earnings - costs of earning = net, posted as income into a tracker)
    db.exec(`
      CREATE TABLE IF NOT EXISTS salary_months (
        id             INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        month          TEXT NOT NULL,                       -- YYYY-MM
        tracker_id     INTEGER REFERENCES trackers(id) ON DELETE SET NULL,
        transaction_id INTEGER REFERENCES transactions(id) ON DELETE SET NULL,  -- the income it created
        use_as_budget  INTEGER NOT NULL DEFAULT 0,
        UNIQUE (user_id, month)
      );
      CREATE TABLE IF NOT EXISTS salary_items (
        id        INTEGER PRIMARY KEY AUTOINCREMENT,
        salary_id INTEGER NOT NULL REFERENCES salary_months(id) ON DELETE CASCADE,
        kind      TEXT NOT NULL CHECK (kind IN ('earning','cost')),
        name      TEXT NOT NULL,
        amount    REAL NOT NULL CHECK (amount >= 0),
        position  INTEGER NOT NULL DEFAULT 0
      );
    `);
    // v7: holdings table redesigned (ticker column); old positions are not kept
    if (!hasColumn('holdings', 'ticker')) {
      db.exec('DROP TABLE holdings');
      db.exec(SCHEMA);
    }
    db.exec(`PRAGMA user_version = ${SCHEMA_VERSION}; COMMIT`);
  } catch (e) {
    db.exec('ROLLBACK');
    throw e;
  }
}
db.exec('PRAGMA foreign_keys = ON;');

